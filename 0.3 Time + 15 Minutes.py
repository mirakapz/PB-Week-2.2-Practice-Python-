#0.3 Time + 15 Minutes
TIME_MINUTES = 60
TIME_HOUR = 24

hour = int(input()) #Слагаме 52
minutes = int(input()) #Слагаме 52

minutes += 15 # 52 Минути + 15 = 67

if minutes >= TIME_MINUTES: # Проверява дали 67 > 60, ДА.
    hour += 1 # Часът се прибавя с 1, защото горното твърдение е TRUE.
    minutes -= TIME_MINUTES # Изважда 67 - 60 = 7. Имаме 7 остатък.

if hour >= TIME_HOUR: # Проверява дали часовете са повече от 24: 52 > 24? ДА. (TRUE)
    hour %= TIME_HOUR # Вместо hour -= ЧАС, Използвам %= ЧАС. (ОБЯСНЕНИЕ ДОЛУ)

print(f"{hour}:{minutes:02d}")

# Използвам %= вместо другото, защото ако (някой ненормалник) реши да подаде ВХОД по голям от 24ч. >
# със -=, ако съм подал 52 - 24 = 28(+1), И го прави 29:07, Това за час е невъзможно.

# Затова със %= става:
# -> Час = 52
# -> Мин = 52
# -> Получаваме 52 мин + 15 = 67 мин и защото 67 > 60, +1 на Часа.
# -> 52 Часа става 53
# -> Със модулно деление %: 53 / 24 = 2.208333..., модулното не го интересуват десетиците.
# -> 2 * 24 = 48 Часа
# -> 53 - 48 = 5 Часа.
# -> Имаме Минутите които са 67 се превръщат, 67 - 60 = 7
# -> :02d го форматира и става 5:07ч. Ако не го направим със %=, си остава 29:07ч.
